int	ft_is_prime(int nb)
{
	int	i;

	i = nb - 1;
	if (nb <= 1)
		return (0);
	if (nb == 2)
		return (1);
	while (nb % i != 0 && i > 1)
	{
		i--;
	}
	return (i == 1);
}
